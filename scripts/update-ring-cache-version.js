/**
 * Hash ring WAV assets and write cache-bust version for web + service worker.
 * Called by scripts/sync-call-rings.js and can run standalone before deploy.
 */
const crypto = require('crypto')
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const soundsDir = path.join(root, 'public', 'sounds')
const incoming = path.join(soundsDir, 'incoming-ring.wav')
const outgoing = path.join(soundsDir, 'outgoing-ring.wav')
const versionTs = path.join(root, 'src', 'lib', 'ringAssetVersion.ts')
const swPath = path.join(root, 'public', 'sw.js')

function hashRingAssets() {
  if (!fs.existsSync(incoming) || !fs.existsSync(outgoing)) {
    console.warn('[ring-cache-version] WAV files missing; skip')
    return null
  }
  const hash = crypto.createHash('sha256')
  hash.update(fs.readFileSync(incoming))
  hash.update(fs.readFileSync(outgoing))
  return hash.digest('hex').slice(0, 12)
}

function writeVersionTs(version) {
  fs.writeFileSync(
    versionTs,
    `/** Auto-generated by scripts/update-ring-cache-version.js — do not edit. */\nexport const RING_ASSET_VERSION = '${version}'\n`,
  )
}

function updateServiceWorker(version) {
  let sw = fs.readFileSync(swPath, 'utf8')
  const marker = '// RING_CACHE_VERSION (auto-updated by scripts/update-ring-cache-version.js)'

  if (!sw.includes(marker)) {
    console.warn('[ring-cache-version] sw.js missing RING_CACHE_VERSION marker; skip SW patch')
    return
  }

  sw = sw.replace(/const RING_CACHE_VERSION = '[^']*';/, `const RING_CACHE_VERSION = '${version}';`)
  fs.writeFileSync(swPath, sw)
}

function main() {
  const version = hashRingAssets()
  if (!version) return null

  writeVersionTs(version)
  updateServiceWorker(version)
  console.log(`[ring-cache-version] ${version}`)
  return version
}

if (require.main === module) {
  const version = main()
  if (!version) process.exit(1)
}

module.exports = { hashRingAssets, main }
