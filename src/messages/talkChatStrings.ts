/**
 * Bundled TalkChat UI copy (same pattern as `feedCardT`). Avoids relying on `/api/translate/text` for chrome.
 */
export function talkChatT(localeTag: string | undefined, key: TalkChatKey): string {
  const primary = (localeTag || 'en').toLowerCase().split('-')[0]
  const pack = MESSAGES[primary] ?? EN
  return pack[key] ?? EN[key]
}

/** Ordered array aligned with `talkChatIdx` — use `tr[talkChatIdx.pubKong]` etc. */
export function talkChatTr(localeTag: string | undefined): readonly string[] {
  return ORDER.map((k) => talkChatT(localeTag, k))
}

export const talkChatIdx = ORDER.reduce<Record<TalkChatKey, number>>((acc, k, i) => {
  acc[k] = i
  return acc
}, {} as Record<TalkChatKey, number>)
